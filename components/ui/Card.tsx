import React from "react";
import { clsx } from "clsx";

export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverEffect?: boolean }
>(({ className, hoverEffect = false, ...props }, ref) => (
  <div
    ref={ref}
    className={clsx(
      "rounded border border-slate-200 bg-white text-slate-800 shadow-sm",
      hoverEffect && "hover:border-slate-300 hover:shadow transition-shadow duration-150",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

